import type { Nutrients } from './nutrition';

export type FoodGroup = 'plant' | 'dairy' | 'egg' | 'fish' | 'meat';

export type CatalogFood = Nutrients & {
  id: string;
  name: string;
  group: FoodGroup;
  portion?: { label: string; grams: number };
};

type Row = [id: string, name: string, kcal: number, protein: number, fat: number, carbs: number, portion?: [string, number]];

function table(group: FoodGroup, rows: Row[]): CatalogFood[] {
  return rows.map(([id, name, kcal, protein, fat, carbs, portion]) => ({
    id: `catalog-${id}`,
    name,
    group,
    kcal,
    protein,
    fat,
    carbs,
    ...(portion ? { portion: { label: portion[0], grams: portion[1] } } : {}),
  }));
}

